
import re

HIGH_RISK_CATEGORIES = {
    "UPFRONT_PAYMENT",
    "OTP_REQUEST",
    "PASSWORD_REQUEST",
    "BANKING_INFORMATION"
}

HIGH_RISK_STATUSES = {
    "UNVERIFIED",
    "DETECTED",
    "FLAGGED",
    "SUSPICIOUS"
}

PAYMENT_PATTERNS = [
    r"registration\s+fee",
    r"application\s+fee",
    r"processing\s+fee",
    r"security\s+deposit",
    r"refundable\s+(?:registration\s+)?fee",
    r"training\s+fee",
    r"upfront\s+payment",
    r"pay\s+(?:before|prior\s+to)\s+(?:joining|interview|selection)",
    r"deposit\s+(?:is\s+)?required",
]

CREDENTIAL_PATTERNS = [
    r"\b(?:share|send|provide|submit)\b.{0,50}\b(?:otp|password|bank\s+details|account\s+details)\b",
    r"\b(?:otp|password)\b.{0,40}\b(?:required|share|send|provide|submit)\b",
    r"\b(?:bank\s+details|bank\s+account\s+details)\b",
]

IDENTITY_PATTERNS = [
    r"\b(?:share|send|submit|upload|provide)\b.{0,60}\b(?:aadhaar|aadhar|pan\s+card)\b",
    r"\b(?:aadhaar|aadhar|pan\s+card)\b.{0,60}\b(?:whatsapp|recruiter|verification)\b",
]


def _has_explicit_request(text, patterns):
    text = str(text or "").lower()

    for pattern in patterns:
        for match in re.finditer(pattern, text):
            preceding = text[max(0, match.start() - 35):match.start()]

            # Avoid flagging explicit statements that say no fee is required.
            if re.search(
                r"\b(?:no|not|never|without|free\s+of)\b"
                r"(?:\s+\w+){0,3}\s*$",
                preceding
            ):
                continue

            return True

    return False


def decide_risk(evidence, checks_completed=False, job_text=""):
    evidence = evidence or []

    # 1. Detect explicit high-risk requests in the job description.
    if (
        _has_explicit_request(job_text, PAYMENT_PATTERNS)
        or _has_explicit_request(job_text, CREDENTIAL_PATTERNS)
        or _has_explicit_request(job_text, IDENTITY_PATTERNS)
    ):
        return "HIGH_CONCERN"

    # 2. Check evidence generated by other verification modules.
    for item in evidence:
        if (
            item.get("category") in HIGH_RISK_CATEGORIES
            and item.get("status") in HIGH_RISK_STATUSES
        ):
            return "HIGH_CONCERN"

    # 3. Conflicting information requires investigation.
    mismatch_categories = {
        "OFFICIAL_VACANCY_VERIFICATION",
        "RECRUITER_EMAIL",
        "COMPANY_WEBSITE",
        "JOB_DESCRIPTION_MISMATCH"
    }

    for item in evidence:
        if (
            item.get("category") in mismatch_categories
            and item.get("status") in (
                "MISMATCH",
                "DETAILS_MISMATCH"
            )
        ):
            return "NEEDS_VERIFICATION"

    # 4. Require all essential checks before LOW_CONCERN.
    vacancy_matched = any(
        item.get("category") == "OFFICIAL_VACANCY_VERIFICATION"
        and item.get("status") == "DETAILS_MATCH"
        for item in evidence
    )

    company_verified = any(
        item.get("category") == "COMPANY_WEBSITE"
        and item.get("status") == "VERIFIED"
        for item in evidence
    )

    recruiter_verified = any(
        item.get("category") == "RECRUITER_EMAIL"
        and item.get("status") == "VERIFIED"
        for item in evidence
    )

    if (
        checks_completed is True
        and vacancy_matched
        and company_verified
        and recruiter_verified
    ):
        return "LOW_CONCERN"

    return "NEEDS_VERIFICATION"
